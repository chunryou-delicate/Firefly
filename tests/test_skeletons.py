def test_parse_swc_columns_and_comments():
    n = sk.parse_swc(forked())
    assert len(n["id"]) == 7
    assert n["id"].tolist() == [1, 2, 3, 4, 5, 6, 7]
    assert n["parent"].tolist() == [-1, 1, 2, 3, 4, 3, 6]
    assert n["xyz"].shape == (7, 3)
    assert n["xyz"][4].tolist() == [400.0, 0.0, 0.0]
    assert n["xyz"].dtype == np.float64          # voxels, written through unchanged
    assert n["radius"].tolist() == [1.0] * 7


def test_parse_swc_rejects_short_rows_and_empty_files():
    with pytest.raises(ValueError, match="7 columns"):
        sk.parse_swc(swc("1 0 0 0 0 1\n"))
    with pytest.raises(ValueError, match="no nodes"):
        sk.parse_swc(swc(""))


def test_parse_swc_accepts_a_path(tmp_path):
    p = tmp_path / "x.swc"
    p.write_text(forked())
    assert len(sk.parse_swc(p)["id"]) == 7
    assert len(sk.parse_swc(str(p))["id"]) == 7


def test_forest_multiple_roots_and_dangling_parent():
    """Two roots, and a parent id that is not in the file, both start trees."""
    n = sk.parse_swc(swc("1 0 0 0 0 1 -1\n2 0 100 0 0 1 1\n"
                         "3 0 0 500 0 1 -1\n4 0 100 500 0 1 3\n"
                         "5 0 0 900 0 1 999\n6 0 100 900 0 1 5\n"))
    paths, n_branch, n_roots = sk.branch_paths(n["id"], n["parent"])
    assert n_roots == 3 and n_branch == 0
    assert len(paths) == 3


def test_cycle_is_rejected():
    n = sk.parse_swc(swc("1 0 0 0 0 1 3\n2 0 100 0 0 1 1\n3 0 200 0 0 1 2\n"))
    with pytest.raises(ValueError, match="cycle"):
        sk.branch_paths(n["id"], n["parent"])


