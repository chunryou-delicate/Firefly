def test_server_md5_header_parsing():
    class H:
        def get_all(self, k):
            return ["crc32c=av9IGg==", "md5=kwhN0kYXTGMgb/WKuU+Rkw=="]
    # the real header observed for bodyId 98113
    assert sk._server_md5(H()) == "93084dd246174c63206ff58ab94f9193"

    class NoMd5:
        def get_all(self, k):
            return ["crc32c=av9IGg=="]
    assert sk._server_md5(NoMd5()) is None
