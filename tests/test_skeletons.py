"""M6a tests: SWC parsing, branch-preserving decimation and bundle output.

Everything here runs on synthetic skeletons and a stub graph — no network, no
downloaded data — so the suite stays fast and deterministic. The contract under
test is docs/m6-3d-contract.md "파일 2"; the pipeline is docs/m6a-brief.md.
"""
import json

import numpy as np
import pytest

from flysim.data import skeletons as sk


# ---------------------------------------------------------------------------
# helpers
# ---------------------------------------------------------------------------
def swc(lines: str) -> str:
    """SWC text with the header comments the real files carry."""
    return ("#Generated by NeuTu (https://github.com/janelia-flyem/NeuTu)\n"
            '#${"ds_intv": [63, 63, 63]}\n\n' + lines)


def straight_line(n: int = 11, step: float = 100.0) -> str:
    """One straight chain along +x: RDP must collapse it to a single segment."""
    out = []
    for i in range(n):
        out.append(f"{i+1} 0 {i*step} 0 0 1 {i if i else -1}")
    return swc("\n".join(out) + "\n")


def forked() -> str:
    """A 'Y': trunk 1-2-3, then two branches. Node 3 is the branch point.

        1 - 2 - 3 - 4 - 5        (+x)
                  \\- 6 - 7       (+y)

    Three branch paths (trunk 1-2-3, arm 3-4-5, arm 3-6-7), so the decimation
    floor is 3 segments however large the tolerance.
    """
    return swc(
        "1 0 0 0 0 1 -1\n"
        "2 0 100 0 0 1 1\n"
        "3 0 200 0 0 1 2\n"
        "4 0 300 0 0 1 3\n"
        "5 0 400 0 0 1 4\n"
        "6 0 200 100 0 1 3\n"
        "7 0 200 200 0 1 6\n")


class StubGraph:
    """Minimal duck-type of flysim.graph.Graph for the bundle tests."""

    def __init__(self, body_ids, soma=None):
        self.body_ids = np.asarray(body_ids, dtype=np.int64)
        n = len(self.body_ids)
        self.soma_xyz = np.full((n, 3), np.nan, dtype=np.float32)
        self.has_soma_xyz = np.zeros(n, dtype=bool)
        for i, v in (soma or {}).items():
            self.soma_xyz[i] = v
            self.has_soma_xyz[i] = True

    def idx(self, body_id):
        b = np.atleast_1d(np.asarray(body_id, dtype=np.int64))
        pos = np.searchsorted(self.body_ids, b)
        if (self.body_ids[np.minimum(pos, len(self.body_ids) - 1)] != b).any():
            raise KeyError("bodyId not in stub graph")
        return pos

    def body(self, idx):
        return self.body_ids[idx]


@pytest.fixture
def patched_download(monkeypatch, tmp_path):
    """Route downloads to files written into tmp_path; no network."""
    store: dict[int, str] = {}

    def fake(body_id, prov, force=False):
        body_id = int(body_id)
        if body_id not in store:
            return None, "missing"
        p = tmp_path / f"{body_id}.swc"
        p.write_text(store[body_id])
        prov[f"{body_id}.swc"] = {"md5": "stub", "bytes": len(store[body_id])}
        return p, "downloaded"

    monkeypatch.setattr(sk, "download_skeleton", fake)
    monkeypatch.setattr(sk, "_save_provenance", lambda p: None)
    monkeypatch.setattr(sk, "_load_provenance", lambda: {})
    return store


