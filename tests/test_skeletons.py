CONTRACT_TOP_KEYS = {"set", "voxel_nm", "n_neurons", "n_segments", "bbox", "decimation",
                     "neurons", "missing", "source", "generated"}
CONTRACT_NEURON_KEYS = {"body_id", "idx", "seg_offset", "seg_count", "soma", "n_nodes_raw"}


def test_bundle_json_has_every_contract_key(patched_download, tmp_path):
    patched_download[100] = forked()
    patched_download[200] = straight_line()
    g = StubGraph([100, 200], soma={0: (1.0, 2.0, 3.0)})
    bin_path, json_path = sk.build_bundle([100, 200], "T", graph=g, out_dir=tmp_path,
                                          max_segments_per_neuron=10_000, progress=False)
    meta = json.loads(json_path.read_text())
    assert CONTRACT_TOP_KEYS <= set(meta)
    assert meta["set"] == "T" and meta["voxel_nm"] == 8 and meta["n_neurons"] == 2
    assert set(meta["bbox"]) == {"min", "max"} and len(meta["bbox"]["min"]) == 3
    assert meta["decimation"]["method"] == "rdp-per-branch"
    assert {"tolerance_voxels", "max_segments_per_neuron"} <= set(meta["decimation"])
    assert meta["source"]["url_prefix"] == sk.URL_PREFIX
    assert meta["source"]["md5_manifest"] == "data-provenance/skeleton-hashes.json"
    for rec in meta["neurons"]:
        assert CONTRACT_NEURON_KEYS <= set(rec)
    assert meta["neurons"][0]["soma"] == [1.0, 2.0, 3.0]
    assert meta["neurons"][1]["soma"] is None


def test_bundle_bin_matches_json_offsets(patched_download, tmp_path):
    patched_download[100] = forked()
    patched_download[200] = straight_line()
    g = StubGraph([100, 200])
    bin_path, json_path = sk.build_bundle([100, 200], "T", graph=g, out_dir=tmp_path,
                                          max_segments_per_neuron=10_000, progress=False)
    meta = json.loads(json_path.read_text())
    buf = np.frombuffer(bin_path.read_bytes(), dtype=np.float32)
    assert buf.size == meta["n_segments"] * 6           # x1 y1 z1 x2 y2 z2
    assert sum(r["seg_count"] for r in meta["neurons"]) == meta["n_segments"]
    off = 0
    for r in meta["neurons"]:                           # offsets are contiguous, in order
        assert r["seg_offset"] == off
        off += r["seg_count"]
    # the straight-line neuron's single segment survives the round trip
    r = [x for x in meta["neurons"] if x["body_id"] == 200][0]
    seg = buf[r["seg_offset"] * 6:(r["seg_offset"] + r["seg_count"]) * 6]
    assert seg.tolist() == [0.0, 0.0, 0.0, 1000.0, 0.0, 0.0]
    assert meta["neurons"][0]["idx"] < meta["neurons"][1]["idx"]   # graph-index order


def test_bundle_drops_body_ids_absent_from_the_graph(patched_download, tmp_path):
    patched_download[100] = forked()
    patched_download[999] = forked()
    g = StubGraph([100, 200])                            # 999 is not a graph neuron
    _, json_path = sk.build_bundle([100, 999], "T", graph=g, out_dir=tmp_path,
                                   max_segments_per_neuron=10_000, progress=False)
    meta = json.loads(json_path.read_text())
    assert [r["body_id"] for r in meta["neurons"]] == [100]
    assert meta["not_in_graph"] == [999]
    with pytest.raises(LookupError, match="retained graph"):
        sk.build_bundle([999], "T2", graph=g, out_dir=tmp_path, progress=False)


