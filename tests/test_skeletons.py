def test_straight_line_collapses_to_one_segment():
    res = sk.simplify_neuron(sk.parse_swc(straight_line(11, 100.0)), tolerance=40.0)
    assert res["n_nodes_raw"] == 11
    assert res["n_branch_points"] == 0 and res["n_roots"] == 1
    assert len(res["segments"]) == 1
    assert res["segments"][0][0].tolist() == [0.0, 0.0, 0.0]
    assert res["segments"][0][1].tolist() == [1000.0, 0.0, 0.0]


def test_branch_points_and_endpoints_are_preserved():
    """Even at a tolerance far larger than the neuron, the Y keeps its fork."""
    res = sk.simplify_neuron(sk.parse_swc(forked()), tolerance=1e6, max_segments=10_000)
    assert res["n_branch_points"] == 1
    assert len(res["segments"]) == res["segment_floor"] == 3
    pts = res["segments"].reshape(-1, 3)
    for required in ([200.0, 0.0, 0.0],        # the branch point
                     [400.0, 0.0, 0.0],        # endpoint of branch 1
                     [200.0, 200.0, 0.0],      # endpoint of branch 2
                     [0.0, 0.0, 0.0]):         # the root
        assert any(np.array_equal(p, required) for p in pts), required


def test_tolerance_is_respected():
    """A point displaced by d is kept when d > tol and dropped when d < tol."""
    d = 50.0
    text = swc(f"1 0 0 0 0 1 -1\n2 0 100 {d} 0 1 1\n3 0 200 0 0 1 2\n")
    n = sk.parse_swc(text)
    keep_tight, dev_tight = sk.rdp_mask(n["xyz"], d / 2)
    keep_loose, dev_loose = sk.rdp_mask(n["xyz"], d * 2)
    assert keep_tight.tolist() == [True, True, True]
    assert keep_loose.tolist() == [True, False, True]
    assert dev_tight == 0.0                      # nothing dropped
    assert dev_loose == pytest.approx(d)         # the dropped point's deviation
    assert dev_loose <= d * 2                    # never exceeds the tolerance


def test_reported_max_deviation_never_exceeds_tolerance():
    rng = np.random.default_rng(0)
    pts = np.cumsum(rng.normal(0, 30, size=(400, 3)), axis=0)
    for tol in (5.0, 40.0, 200.0):
        keep, dev = sk.rdp_mask(pts, tol)
        assert dev <= tol + 1e-9
        assert keep[0] and keep[-1]
        # The RDP guarantee, checked point by point: every dropped point lies
        # within tol of the infinite line through the retained pair that brackets
        # it (that pair is exactly the span the recursion accepted). Note this is
        # NOT the clamped distance to the nearest retained segment, which classic
        # RDP does not bound and which can legitimately exceed tol.
        kept_idx = np.flatnonzero(keep)
        for i in np.flatnonzero(~keep):
            a = pts[kept_idx[kept_idx < i][-1]]
            b = pts[kept_idx[kept_idx > i][0]]
            assert _line_distance(pts[i], a, b) <= tol + 1e-6
    # a looser tolerance never keeps more points
    counts = [int(sk.rdp_mask(pts, t)[0].sum()) for t in (5.0, 40.0, 200.0)]
    assert counts == sorted(counts, reverse=True)


def _line_distance(p, a, b):
    """Perpendicular distance from p to the infinite line through a and b."""
    s = b - a
    l2 = float(s @ s)
    if l2 <= 0:
        return float(np.linalg.norm(p - a))
    return float(np.linalg.norm((p - a) - ((p - a) @ s / l2) * s))


def test_segment_cap_raises_tolerance_and_stops_at_the_branch_floor():
    """A 100-node zigzag exceeds a cap of 5 at tol 1, so the tolerance is raised."""
    pts = [(i * 100.0, (i % 2) * 300.0, 0.0) for i in range(100)]
    text = swc("\n".join(f"{i+1} 0 {x} {y} {z} 1 {i if i else -1}"
                         for i, (x, y, z) in enumerate(pts)) + "\n")
    n = sk.parse_swc(text)
    loose = sk.simplify_neuron(n, tolerance=1.0, max_segments=5)
    assert loose["tolerance_steps"] > 0
    assert loose["tolerance_voxels"] > 1.0
    assert len(loose["segments"]) <= 5 and loose["cap_met"]
    # an unbranched chain can always reach 1 segment, so the floor is not binding here
    assert loose["segment_floor"] == 1


def test_cap_below_the_branch_floor_is_reported_not_faked():
    """The floor is one segment per branch path; RDP cannot go below it, and the
    result says so rather than pruning branches to fit (docs/m6a-report.md)."""
    res = sk.simplify_neuron(sk.parse_swc(forked()), tolerance=40.0, max_segments=1)
    assert res["segment_floor"] == 3
    assert len(res["segments"]) == 3             # branch points still preserved
    assert res["cap_met"] is False
    assert res["n_branch_points"] == 1


